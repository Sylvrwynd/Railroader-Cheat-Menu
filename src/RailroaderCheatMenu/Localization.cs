        internal static MenuLanguage Current { get; private set; } = MenuLanguage.English;

        internal static string LanguageName
        {
            get
            {
                switch (Current)
                {
                    case MenuLanguage.German: return "Deutsch";
                    case MenuLanguage.Spanish: return "Español";
                    case MenuLanguage.TraditionalChinese: return "繁體中文";
                    case MenuLanguage.Russian: return "Русский";
                    case MenuLanguage.French: return "Français";
                    default: return "English";
                }
            }
        }

        internal static void Toggle()
        {
            Current = (MenuLanguage)(((int)Current + 1) % 6);
        }

        internal static string Text(string key)
        {
            var dictionary = GetCurrentDictionary();
            if (dictionary.TryGetValue(key, out var translated))
            {
                return translated;
            }

            return English.TryGetValue(key, out var value) ? value : key;
        }

        internal static string Format(string key, params object[] values)
        {
            return string.Format(Text(key), values);
        }

        private static Dictionary<string, string> GetCurrentDictionary()
        {
            switch (Current)
            {
                case MenuLanguage.German: return German;
                case MenuLanguage.Spanish: return Spanish;
                case MenuLanguage.TraditionalChinese: return TraditionalChinese;
                case MenuLanguage.Russian: return Russian;
                case MenuLanguage.French: return French;
                default: return English;
            }
        }
